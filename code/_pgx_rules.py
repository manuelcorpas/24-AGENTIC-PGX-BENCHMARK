#!/usr/bin/env python3
"""
Pure pharmacogenomic rule logic, shared by the revision runners.

Why this module exists: the original skill-arm runner (41-armA9-armBv2.py)
constructs five API clients at import time, so importing it requires every
provider key to be present. That makes it impossible to import for a dry run or
a test. This module holds the parts that are pure functions of the case file
(no keys, no network, no side effects at import) so 60-, 61- and 62- can share
them and be tested offline.

norm_dip() is a verbatim copy of the function in 41-armA9-armBv2.py, kept
identical so the reused skill-arm data and the new matched cells normalise
diplotypes the same way. tests/test_matched_factorial.py asserts the two
sources still agree character for character.
"""
from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
CASES_FILE = BASE / "specs" / "test_cases_v3.json"


def norm_dip(s, gene):
    s = (s or "").lower().replace(gene.lower(), "")
    s = re.sub(r"\(.*?\)", "", s).replace("hla-", "")
    s = s.replace("positive", "pos").replace("negative", "neg").replace("carrier", "").replace("present", "pos").replace("absent", "neg")
    s = re.sub(r"[^\w*/:.\- ]", "", s)
    parts = [re.sub(r"\s+", "", p) for p in re.split(r"\s*/\s*", s) if p.strip()]
    if len(parts) == 2: parts = sorted(parts)
    return "/".join(parts) if parts else re.sub(r"\s+", "", s)


def load_cases(path: Path | None = None) -> list[dict]:
    return json.loads((path or CASES_FILE).read_text())


def build_rules(cases: list[dict]):
    """Return (dip2phen, rec, rules_dip, rules_rec) exactly as 41- builds them."""
    dip2phen: dict[tuple[str, str], str] = {}
    rec: dict[tuple[str, str, str], str] = {}
    rules_dip: dict[str, dict[str, str]] = defaultdict(dict)
    rules_rec: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for c in cases:
        g = c["gene"]
        nd = norm_dip(c["gt_diplotype"], g)
        dip2phen[(g, nd)] = c["gt_phenotype"]
        rec[(g, c["drug"], nd)] = c["gt_drug"]
        rules_dip[g][c["gt_diplotype"]] = c["gt_phenotype"]
        rules_rec[g].append((c["drug"], c["gt_diplotype"], c["gt_drug"]))
    return dip2phen, rec, rules_dip, rules_rec


def skill_rules_text(gene: str, rules_dip, rules_rec) -> str:
    """The validated skill's rule table, as shown to the skill-reasoning arm."""
    lines = [f"# SKILL: {gene} (validated rules)", "## Rule 1 diplotype -> phenotype"]
    for dip, ph in sorted(rules_dip[gene].items()):
        lines.append(f"  {dip} -> {ph}")
    lines.append("## Rule 2 (drug, diplotype) -> recommendation")
    seen = set()
    for drug, dip, rec in rules_rec[gene]:
        if (drug, dip) in seen:
            continue
        seen.add((drug, dip))
        lines.append(f"  ({drug}, {dip}) -> {rec}")
    return "\n".join(lines)


def parse_field(text: str, field: str, allow_bare: bool = False) -> str:
    """Extract a labelled field, optionally accepting an unlabelled answer.

    Why allow_bare exists: asked for "DIPLOTYPE: [x]", GPT-4.1 frequently
    answered just "*1/*4". The call was correct; only the label was missing. A
    strict parser recorded that as an empty call, the pipeline abstained, and
    the model's score collapsed from ~0.99 to 0.44. That is a format artefact
    presented as a model failure, which is the exact error class this paper
    exists to warn about, so the parser must not commit it.

    Format compliance is still measured, separately, by is_format_compliant().
    """
    if not text:
        return ""
    for line in text.split("\n"):
        if (field + ":") in line.upper():
            return line[line.upper().index(field + ":") + len(field) + 1:].strip()
    if allow_bare:
        stripped = text.strip()
        # Only for a terse single-line reply that carries no field labels at
        # all: never salvage a value out of prose that answered something else.
        if "\n" not in stripped and ":" not in stripped and len(stripped) <= 40:
            return stripped
    return ""


def is_format_compliant(text: str, field: str) -> bool:
    """Did the response actually use the requested label?"""
    return bool(text) and (field + ":") in text.upper()


def make_executor(dip2phen, rec):
    """Return execute_skill(gene, drug, diplotype) -> (phenotype, recommendation).

    This IS the versioned skill's mapping step, executed in code rather than
    generated by a model. It abstains (returns (None, None)) on any diplotype
    outside the validated vocabulary, which is the same abstention contract as
    the N0 end-to-end pipeline: out of vocabulary must not become a guess.
    """
    def execute_skill(gene: str, drug: str, diplotype: str):
        nd = norm_dip(diplotype, gene)
        if not nd:
            return None, None
        phen = dip2phen.get((gene, nd))
        recommendation = rec.get((gene, drug, nd))
        if phen is None or recommendation is None:
            return None, None
        return phen, recommendation
    return execute_skill


# =============================================================================
# Retrieval chunking (revision item N4; R1.2, R2.3)
# =============================================================================
# Gene-keyed retrieval hands the model every drug annotation for the gene: the
# CYP2D6 excerpt is 24,781 characters covering codeine, tamoxifen, ondansetron,
# paroxetine and more. The model must then pick the right drug's table itself,
# and the drug-substitution failure reported in the paper is partly an artefact
# of that indexing choice rather than a property of retrieval as such.
#
# Drug-keyed chunking retrieves only the annotation section for the queried
# drug. Ported from 16b-rag-genedrug-chunking.py, which established the effect
# on six genes; N4 extends it to the full grid and makes it the primary
# retrieval arm, with the gene-keyed configuration retained as an ablation.

def split_chunks(excerpt: str) -> dict[str, str]:
    """Split a gene excerpt into {drug: annotation section}."""
    out: dict[str, str] = {}
    for part in re.split(r"(?=^### Annotation)", excerpt, flags=re.M):
        if not part.strip():
            continue
        m = re.search(r"Drug scope:\s*([^\n]+)", part)
        if not m:
            continue
        for d in re.split(r"[;,/]| and ", m.group(1)):
            d = d.strip().lower()
            if d:
                out[d] = part
    return out


# Four benchmark cases query a drug CLASS while the CPIC corpus is indexed by
# individual agents. This is part of the drug-substitution story rather than a
# nuisance: a model asked about "thiopurines" and shown a page headed
# "azathioprine" must make a class-to-member inference. The mapping is declared
# here explicitly so it is auditable, and retrieval records which route it took.
DRUG_CLASS_ALIASES: dict[str, list[str]] = {
    "thiopurines": ["azathioprine"],
    "aminoglycosides": ["amikacin", "dibekacin", "gentamicin", "kanamycin", "neomycin",
                        "netilmicin", "paromomycin", "plazomicin", "ribostamycin",
                        "streptomycin", "tobramycin"],
    "volatile-anaesthetics": ["desflurane", "enflurane", "halothane", "isoflurane",
                              "methoxyflurane", "sevoflurane", "succinylcholine"],
    "peg-ifn-\u03b1": ["peginterferon alfa-2a", "peginterferon alfa-2b"],
}


def drug_chunk(excerpt: str, drug: str) -> tuple[str | None, str]:
    """Retrieve the annotation section(s) for one drug.

    Returns (chunk, route) where route is one of:
      "exact"  the corpus has a section for this drug name
      "class"  the query is a drug class; the member sections are concatenated
      "none"   no section found; the caller must fall back and record that it did

    Never returns a silent fallback: a caller that ignores `route` and reports
    drug-keyed coverage as 100% would be misreporting the experiment.
    """
    chunks = split_chunks(excerpt)
    key = drug.strip().lower()
    if key in chunks:
        return chunks[key], "exact"
    members = [chunks[m] for m in DRUG_CLASS_ALIASES.get(key, []) if m in chunks]
    if members:
        return "\n\n".join(members), "class"
    return None, "none"
